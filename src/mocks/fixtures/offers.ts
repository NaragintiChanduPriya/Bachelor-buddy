import type { OfferKind, OfferPlatformCategory } from '@/types/offer'
import { daysAgo, daysAhead } from '../clock'

/**
 * Stored offer terms. Everything that depends on the user or the clock — days left, whether
 * it is expiring, eligibility for the user's cards, the worked example — is derived on read.
 */
export interface OfferRecord {
  id: string
  kind: OfferKind
  title: string
  description: string
  platform: string
  platformCategory: OfferPlatformCategory
  bank: string | null
  cardType: 'credit' | 'debit' | null
  code: string | null
  discountPercent: number | null
  flatDiscount: number | null
  maxDiscount: number | null
  minOrderValue: number
  validFrom: string
  validTill: string
}

