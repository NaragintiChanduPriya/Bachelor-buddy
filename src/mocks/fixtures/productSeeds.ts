import type { ProductCategory } from '@/types/product'

export type ShoppingPlatform = 'ShopNest' | 'TrendKart' | 'StyleBay'

/**
 * How a product's price moved over the last 90 days. The pattern drives the history generator,
 * and the history drives the verdict — so the buy/wait mix comes from real-looking data rather
 * than a hard-coded flag.
 * - steady: flat with small weekly changes (buy now: waiting saves little)
 * - inSale: a recurring sale is running today (buy now)
 * - afterSale: a recurring sale ended recently and the price is back up (wait)
 * - festivalSpike: seasonal demand has pushed the price up over the last few weeks (wait)
 * - recentDrop: a one-off cut to a 90-day low in the last few days (buy now)
 */
export type PricePattern = 'steady' | 'inSale' | 'afterSale' | 'festivalSpike' | 'recentDrop'

export interface ProductSeed {
  id: string
  name: string
  brand: string
  category: ProductCategory
  mrp: number
  /** Normal, non-sale price on the primary platform. */
  basePrice: number
  primary: ShoppingPlatform
  pattern: PricePattern
  /** Exact low the primary platform sells at during a sale or after a drop. */
  lowPrice?: number
  /** Normal price on the other platforms, when it should be exact rather than generated. */
  platformPrices?: Partial<Record<ShoppingPlatform, number>>
  /** Platforms listing the product. Defaults to all three. */
  platforms?: ShoppingPlatform[]
  sponsoredOn?: ShoppingPlatform
  /** Arrives before the coming Friday on the primary platform. */
  fastDelivery?: boolean
  outOfStockOn?: ShoppingPlatform
  description: string
  highlights: string[]
}

