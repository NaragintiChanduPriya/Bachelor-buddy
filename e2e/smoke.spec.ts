import { expect, test, type Page } from '@playwright/test'

/**
 * Signs up as Arjun through the real four-step onboarding, leaving the browser on the
 * dashboard. Each test gets a fresh context, so this runs per test.
 */
async function onboardAsArjun(page: Page) {
  await page.goto('/onboarding')
  await page.getByRole('button', { name: 'Get started' }).click()
  await page.getByLabel(/Monthly salary/).fill('40000')
  await page.getByLabel(/savings goal/i).fill('8000')
  await page.getByRole('button', { name: 'Continue' }).click()
  await page.getByLabel('Where do you live?').click()
  await page.getByRole('option', { name: 'HSR Layout', exact: true }).click()
  await page.getByLabel('Where do you work?').click()
  await page.getByRole('option', { name: 'Bellandur', exact: true }).click()
  await page.getByRole('button', { name: 'Continue' }).click()
  await page
    .getByRole('radio', { name: /Vegetarian/ })
    .first()
    .check()
  await page.getByRole('button', { name: /Create my budget/ }).click()
  await expect(page.getByText('left this month')).toBeVisible({ timeout: 30_000 })
}

test.describe('onboarding', () => {
  test('sends a new user to onboarding and through all four steps', async ({ page }) => {
    await page.goto('/')
    await expect(page).toHaveURL(/\/onboarding$/)

    await page.getByRole('button', { name: 'Get started' }).click()
    await expect(page.getByRole('heading', { name: 'What are you working with?' })).toBeVisible()

    await page.getByLabel(/Monthly salary/).fill('40000')
    await page.getByLabel(/savings goal/i).fill('8000')
    await page.getByRole('button', { name: 'Continue' }).click()

    await expect(page.getByRole('heading', { name: 'Where are you based?' })).toBeVisible()
    await page.getByLabel('Where do you live?').click()
    await page.getByRole('option', { name: 'HSR Layout', exact: true }).click()
    await page.getByLabel('Where do you work?').click()
    await page.getByRole('option', { name: 'Bellandur', exact: true }).click()
    await page.getByRole('button', { name: 'Continue' }).click()

    await expect(page.getByRole('heading', { name: 'Last bit' })).toBeVisible()
    await page
      .getByRole('radio', { name: /Vegetarian/ })
      .first()
      .check()
    await page.getByRole('button', { name: /Create my budget/ }).click()

    // Lands on the dashboard with a real budget generated by the server.
    await expect(page.getByText('left this month')).toBeVisible({ timeout: 30_000 })
    await expect(page).toHaveURL(/\/$/)
  })

  test('rejects a savings goal that is not less than the salary', async ({ page }) => {
    await page.goto('/onboarding')
    await page.getByRole('button', { name: 'Get started' }).click()

    await page.getByLabel(/Monthly salary/).fill('40000')
    await page.getByLabel(/savings goal/i).fill('40000')
    await page.getByRole('button', { name: 'Continue' }).click()

    await expect(page.getByText(/must be less than your salary/)).toBeVisible()
    await expect(page.getByRole('heading', { name: 'What are you working with?' })).toBeVisible()
  })
})

test.describe('dashboard', () => {
  test('loads the budget from the mock backend', async ({ page }) => {
    await onboardAsArjun(page)

    await expect(page.getByText(/Good (morning|afternoon|evening|night), Arjun/)).toBeVisible()
    await expect(page.getByText('Watch these this month')).toBeVisible()

    // The targets fixed in CLAUDE.md: food about 70% used, shopping with Rs 1,800 left.
    // The progressbar's accessible name carries the percentage the server computed.
    await expect(page.getByRole('progressbar', { name: 'Food: 70% of budget used' })).toBeVisible()

    // Every category, shopping included, is on the Budget page.
    await page.goto('/budget')
    await expect(page.getByText('₹1,800', { exact: true }).first()).toBeVisible({ timeout: 30_000 })
  })

  test('the API returns the standard envelope', async ({ page }) => {
    // POST /onboarding returns the generated budget and seeds the query cache, so the
    // dashboard never needs a separate GET /budget/current on this path.
    const response = page.waitForResponse((r) => r.url().includes('/onboarding'))
    await onboardAsArjun(page)
    const body = await (await response).json()

    expect(body).toMatchObject({ success: true, meta: null, error: null })
    expect(body.data.budget).toHaveProperty('categories')
    expect(body.data.budget.categories[0]).toHaveProperty('percentUsed')
    expect(body.data.user).toHaveProperty('onboarded', true)
  })

  test('logging an expense updates the budget everywhere', async ({ page }) => {
    await onboardAsArjun(page)

    await expect(page.getByText('₹14,980')).toBeVisible()
    await expect(page.getByRole('progressbar', { name: 'Food: 70% of budget used' })).toBeVisible()

    await page.getByRole('button', { name: 'Log expense' }).click()
    await page.getByLabel('What was it?').fill('Test dinner')
    await page.getByLabel(/Amount/).fill('500')
    await page.getByRole('button', { name: 'Add expense' }).click()

    // Hero and the food bar both move off one mutation: 5,250 + 500 = 5,750 of 7,500 = 77%.
    await expect(page.getByText('₹14,480')).toBeVisible({ timeout: 30_000 })
    await expect(page.getByRole('progressbar', { name: 'Food: 77% of budget used' })).toBeVisible()

    await page.getByRole('link', { name: 'Expenses' }).click()
    await expect(page.getByText('Test dinner')).toBeVisible({ timeout: 30_000 })
  })
})

test.describe('app shell', () => {
  test('navigates between routes', async ({ page }) => {
    await onboardAsArjun(page)
    await page.getByRole('link', { name: 'Food', exact: true }).first().click()
    await expect(page).toHaveURL(/\/food$/)
    await expect(page.getByRole('heading', { name: 'Food', level: 1 })).toBeVisible()
  })

  test('filters expenses through the URL', async ({ page }) => {
    await onboardAsArjun(page)
    await page.goto('/expenses')
    await page.getByLabel('Category').click()
    await page.getByRole('option', { name: 'Food', exact: true }).click()

    await expect(page).toHaveURL(/category=food/)
    // The food total matches the budget's food spend exactly.
    await expect(page.getByText('₹5,250')).toBeVisible({ timeout: 30_000 })
  })

  test('shows a 404 page for an unknown route', async ({ page }) => {
    await onboardAsArjun(page)
    await page.goto('/this-route-does-not-exist')
    await expect(page.getByRole('heading', { name: "We can't find that page" })).toBeVisible()
  })

  test('has a working skip link', async ({ page }) => {
    await onboardAsArjun(page)
    await page.evaluate(() => (document.activeElement as HTMLElement | null)?.blur())
    await page.keyboard.press('Tab')

    const skipLink = page.getByRole('link', { name: 'Skip to content' })
    await expect(skipLink).toBeFocused()

    await page.keyboard.press('Enter')
    await expect(page.locator('#main-content')).toBeFocused()
  })
})
